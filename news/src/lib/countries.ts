const findCountry = (value?: string) => {
  const key = String(value || '').trim()
  if (!key) return undefined
  const upper = key.toUpperCase()
  const lower = key.toLowerCase()
  return (
    COUNTRIES.find((row) => row.code === upper) ||
    COUNTRIES.find((row) => row.es.toLowerCase() === lower || row.en.toLowerCase() === lower)
  )
}

export const countryCode = (value?: string) => findCountry(value)?.code || ''

export const countryFlag = (value?: string) => {
  const code = findCountry(value)?.code
  if (!code) return ''
  return [...code.toUpperCase()].map((letter) => String.fromCodePoint(127397 + letter.charCodeAt(0))).join('')
}

export const countryLabel = (value?: string, locale: 'es' | 'en' = 'es') => {
  const row = findCountry(value)
  if (!row) return String(value || '').trim()
  return locale === 'en' ? row.en : row.es
}

export const countriesFor = (locale: 'es' | 'en' = 'es') =>
  [...COUNTRIES].sort((a, b) => (locale === 'en' ? a.en : a.es).localeCompare(locale === 'en' ? b.en : b.es, locale))
